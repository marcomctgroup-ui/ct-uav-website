"""Batch 2 (hosting headers) for main website refactor v04. 5 November 2026.

Writes refactor-v04/_headers in Netlify format. Run again after any asset or library change:
    python projects/main-website/refactor-v06/source-code/20261105-batch2-headers-build.py

Cache rules:
- index.html, / and pages/*: no-cache (always revalidate).
- Asset files whose name token is a real content hash (checked against sha256/md5/sha1 of the
  bytes on every run): one year, immutable.
- All other assets: no rule, so the host default applies (always revalidate).
  Many v03 names look hashed but were edited in place; they do not get a long cache.
No path matches two Cache-Control rules, because Netlify combines values of rules that overlap.
The CSP hashes use the exact file bytes (CRLF). A deploy step must not change line endings.
Run this script again after any asset, library or inline-script change.

Security rules for every path: Content-Security-Policy, X-Content-Type-Options,
Referrer-Policy, Permissions-Policy, X-Frame-Options.
The CSP allows only this site's own files. Injected library scripts and the one inline
script are allowed by SHA-256 hash. WebAssembly and blob workers are needed by the 3D decoder.
"""
import base64, hashlib, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HASHED = re.compile(r'-[0-9a-f]{10,12}(-[a-z0-9]+)?\.[a-z0-9]+$')
IMMUTABLE = 'public, max-age=31536000, immutable'
REVALIDATE = 'no-cache'


def sha(text):
    return "'sha256-" + base64.b64encode(hashlib.sha256(text.encode('utf-8')).digest()).decode() + "'"


# Inline and injected scripts that must run under the policy.
index = (ROOT / 'index.html').read_bytes().decode('utf-8')
inline = [m.group(2) for m in re.finditer(r'<script\b([^>]*)>(.*?)</script>', index, re.S)
          if 'src=' not in m.group(1) and 'type=' not in m.group(1) and m.group(2).strip()]
if len(inline) != 1:
    sys.exit(f'STOP: expected 1 inline script in index.html, found {len(inline)}')
for page in sorted((ROOT / 'pages').glob('*.html')):
    s = page.read_text(encoding='utf-8')
    extra = [m for m in re.finditer(r'<script\b([^>]*)>(.*?)</script>', s, re.S)
             if 'src=' not in m.group(1) and 'type=' not in m.group(1) and m.group(2).strip()]
    if extra:
        sys.exit(f'STOP: {page.name} has an inline script; add its hash first')
injected = [next((ROOT / 'assets/js').glob(n)) for n in ('uav3dlib*.js', 'ctencymeshopt*.js')]  # names carry a content hash since v05 r02
hashes = [sha(inline[0])] + [sha(p.read_bytes().decode('utf-8')) for p in injected]  # exact bytes: keep CRLF

csp = '; '.join([
    "default-src 'self'",
    "script-src 'self' 'wasm-unsafe-eval' " + ' '.join(hashes),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    "media-src 'self'",
    "connect-src 'self' blob: data: https://api.storyblok.com",  # GLTFLoader reads embedded textures by blob: URL; Storyblok CMS pilot fetch (pages/decarb22.html)
    "worker-src 'self' blob:",
    "frame-src 'self'",
    "frame-ancestors 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
])

lines = ['# Generated by source-code/20261105-batch2-headers-build.py. Do not edit by hand.', '',
         '/*',
         f'  Content-Security-Policy: {csp}',
         '  X-Content-Type-Options: nosniff',
         '  Referrer-Policy: strict-origin-when-cross-origin',
         '  Permissions-Policy: camera=(), microphone=(self), geolocation=(), payment=(), usb=()',
         '  X-Frame-Options: SAMEORIGIN',
         '  X-Robots-Tag: noindex',  # Batch 5A: staging only. Remove before the approved public launch.
         '']
# Batch 5A: route folders (products/decarb-22/ and others) hold entry pages; always revalidate.
entry_folders = sorted({q.relative_to(ROOT).parts[0] for q in ROOT.glob('*/**/index.html')
                        if q.relative_to(ROOT).parts[0] not in ('assets', 'pages', 'checks', 'source-code', 'source-inputs')})
for path in ['/', '/index.html', '/pages/*'] + [f'/{f}/*' for f in entry_folders]:
    lines += [path, f'  Cache-Control: {REVALIDATE}', '']

def content_hashed(f):
    """True only when the hex token in the name is a prefix of the file's own sha256, md5 or sha1.
    A file edited in place keeps its old name, fails this test and loses the long cache."""
    m = HASHED.search(f.name)
    if not m:
        return False
    token = re.search(r'-([0-9a-f]{10,12})(?:-[a-z0-9]+)?\.[a-z0-9]+$', f.name).group(1)
    data = f.read_bytes()
    return any(h(data).hexdigest().startswith(token) for h in (hashlib.sha256, hashlib.md5, hashlib.sha1))


# Only verified content-hashed files get a rule. All other assets have no Cache-Control rule,
# so the host default applies (Netlify: public, max-age=0, must-revalidate). No rule overlaps.
counts = {'immutable': 0, 'host_default': 0}
for folder in ['css', 'js', 'img', 'fonts', 'models', 'video']:
    for f in sorted((ROOT / 'assets' / folder).rglob('*')):
        if not f.is_file():
            continue
        if content_hashed(f):
            counts['immutable'] += 1
            lines += [f'/{f.relative_to(ROOT).as_posix()}', f'  Cache-Control: {IMMUTABLE}', '']
        else:
            counts['host_default'] += 1

(ROOT / '_headers').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print('immutable (verified content hash)', counts['immutable'], 'host default', counts['host_default'])
print('script hashes', len(hashes))
